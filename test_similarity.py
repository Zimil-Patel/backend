# ---------------------------------------------------------
# COSINE SIMILARITY
# ---------------------------------------------------------


def cosine_similarity(
    embedding_a,
    embedding_b,
):
    """
    Calculate cosine similarity between two face embeddings.

    The result is generally between -1 and 1.

    Higher value:
        More similar

    Lower value:
        Less similar
    """

    # Convert the first embedding into a NumPy array.
    a = np.asarray(
        embedding_a,
        dtype=np.float32,
    )

    # Convert the second embedding into a NumPy array.
    b = np.asarray(
        embedding_b,
        dtype=np.float32,
    )

    # Calculate the dot product.
    dot_product = np.dot(
        a,
        b,
    )

    # Calculate the magnitude of the first vector.
    magnitude_a = np.linalg.norm(a)

    # Calculate the magnitude of the second vector.
    magnitude_b = np.linalg.norm(b)

    # Prevent division by zero.
    if magnitude_a == 0 or magnitude_b == 0:
        return 0.0

    # Cosine similarity formula:
    #
    #       A · B
    # -----------------
    #    |A| × |B|
    #
    return dot_product / (magnitude_a * magnitude_b)


