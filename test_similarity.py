            embedding_1 = face_1.embedding
            embedding_2 = face_2.embedding

            # Calculate similarity.
            similarity = cosine_similarity(
                embedding_1,
                embedding_2,
            )

            print(f"    ↔ Face {index_2 + 1} from Image 2: {similarity:.4f}")


